/**
 * The LMS side of a SCORM *import*, for statically generated courses.
 *
 * The reader gets this from `@tutors/scorm`, but a `tutors-lite` site has no Svelte and no
 * database, so the same run-time is emitted here as one standalone ES5 file that keeps a
 * learner's state in `localStorage`. The two implementations deliberately share a storage
 * key format, so a learner who moves between the static build and the reader for the same
 * course keeps their progress in each browser.
 *
 * As in `runtime.ts`, generated code avoids template literals and `let`/`const` so that it
 * runs unmodified wherever the content does.
 */

/** Filename written to the course root. */
export const LMS_RUNTIME_FILE = "tutors-scorm-lms.js";

/**
 * Emit the run-time.
 *
 * One script serves both profiles: it publishes `window.API` and `window.API_1484_11`
 * according to the version the page declares in `window.TUTORS_SCORM`, which lets a course
 * mix 1.2 and 2004 packages without generating a file per page.
 */
export function buildLmsRuntimeScript(): string {
  return `/* Generated by Tutors. Browser-local SCORM run-time for static courses. */
(function (global) {
  "use strict";

  var config = global.TUTORS_SCORM || {};
  var IS_2004 = String(config.version) === "2004";
  var STORAGE_KEY = "tutors-scorm:" + (config.courseId || "course") + ":" + (config.loId || "lo");

  /* ---- Profile bindings ------------------------------------------------ */

  var B = IS_2004
    ? {
        learnerId: "cmi.learner_id",
        learnerName: "cmi.learner_name",
        location: "cmi.location",
        sessionTime: "cmi.session_time",
        totalTime: "cmi.total_time",
        exit: "cmi.exit",
        entry: "cmi.entry",
        masteryScore: "cmi.scaled_passing_score"
      }
    : {
        learnerId: "cmi.core.student_id",
        learnerName: "cmi.core.student_name",
        location: "cmi.core.lesson_location",
        sessionTime: "cmi.core.session_time",
        totalTime: "cmi.core.total_time",
        exit: "cmi.core.exit",
        entry: "cmi.core.entry",
        masteryScore: "cmi.student_data.mastery_score"
      };

  var DEFAULTS_12 = {
    "cmi.core.lesson_status": "not attempted",
    "cmi.core.entry": "ab-initio",
    "cmi.core.credit": "credit",
    "cmi.core.lesson_mode": "normal",
    "cmi.core.lesson_location": "",
    "cmi.core.score.raw": "",
    "cmi.core.score.min": "",
    "cmi.core.score.max": "",
    "cmi.core.total_time": "00:00:00.00",
    "cmi.suspend_data": "",
    "cmi.launch_data": "",
    "cmi.student_data.mastery_score": "",
    "cmi.student_preference.audio": "0",
    "cmi.student_preference.language": "",
    "cmi.student_preference.speed": "0",
    "cmi.student_preference.text": "0"
  };

  var DEFAULTS_2004 = {
    "cmi.completion_status": "unknown",
    "cmi.success_status": "unknown",
    "cmi.entry": "ab-initio",
    "cmi.credit": "credit",
    "cmi.mode": "normal",
    "cmi.location": "",
    "cmi.progress_measure": "",
    "cmi.score.raw": "",
    "cmi.score.min": "",
    "cmi.score.max": "",
    "cmi.score.scaled": "",
    "cmi.total_time": "PT0S",
    "cmi.suspend_data": "",
    "cmi.launch_data": "",
    "cmi.scaled_passing_score": "",
    "cmi.completion_threshold": "",
    "cmi.learner_preference.audio_level": "1",
    "cmi.learner_preference.language": "",
    "cmi.learner_preference.delivery_speed": "1",
    "cmi.learner_preference.audio_captioning": "0"
  };

  var READ_ONLY_12 = ["cmi.core.student_id", "cmi.core.student_name", "cmi.core.credit", "cmi.core.entry",
    "cmi.core.total_time", "cmi.core.lesson_mode", "cmi.launch_data", "cmi.comments_from_lms",
    "cmi.student_data.mastery_score", "cmi.student_data.max_time_allowed", "cmi.student_data.time_limit_action"];
  var READ_ONLY_2004 = ["cmi.learner_id", "cmi.learner_name", "cmi.credit", "cmi.entry", "cmi.mode",
    "cmi.total_time", "cmi.launch_data", "cmi.max_time_allowed", "cmi.time_limit_action",
    "cmi.scaled_passing_score", "cmi.completion_threshold"];
  var WRITE_ONLY_12 = ["cmi.core.exit", "cmi.core.session_time"];
  var WRITE_ONLY_2004 = ["cmi.exit", "cmi.session_time"];

  var CHILDREN = {
    "cmi.core._children": "student_id,student_name,lesson_location,credit,lesson_status,entry,score,total_time,lesson_mode,exit,session_time",
    "cmi.core.score._children": "raw,min,max",
    "cmi.objectives._children": "id,score,status",
    "cmi.interactions._children": "id,objectives,time,type,correct_responses,weighting,student_response,result,latency",
    "cmi.student_data._children": "mastery_score,max_time_allowed,time_limit_action",
    "cmi.student_preference._children": "audio,language,speed,text",
    "cmi.score._children": "scaled,raw,min,max",
    "cmi.comments_from_learner._children": "comment,location,timestamp",
    "cmi.comments_from_lms._children": "comment,location,timestamp",
    "cmi.learner_preference._children": "audio_level,language,delivery_speed,audio_captioning"
  };

  var readOnly = IS_2004 ? READ_ONLY_2004 : READ_ONLY_12;
  var writeOnly = IS_2004 ? WRITE_ONLY_2004 : WRITE_ONLY_12;

  function contains(list, value) {
    for (var i = 0; i < list.length; i += 1) if (list[i] === value) return true;
    return false;
  }

  /* ---- Storage --------------------------------------------------------- */

  /* Storage is unavailable in private browsing and sandboxed frames; the attempt
     continues in memory rather than the SCO failing to run. */
  var memory = null;

  function load() {
    try {
      var raw = global.localStorage.getItem(STORAGE_KEY);
      return raw ? JSON.parse(raw) : {};
    } catch (e) {
      return memory || {};
    }
  }

  function persist(snapshot) {
    memory = snapshot;
    try {
      global.localStorage.setItem(STORAGE_KEY, JSON.stringify(snapshot));
    } catch (e) {
      /* Nothing further to do. */
    }
  }

  /* ---- Durations ------------------------------------------------------- */

  function pad(value) {
    return value < 10 ? "0" + value : String(value);
  }

  function formatDuration(seconds) {
    var hours = Math.floor(seconds / 3600);
    var minutes = Math.floor((seconds % 3600) / 60);
    var secs = Math.floor(seconds % 60);
    if (IS_2004) {
      var out = "PT";
      if (hours) out += hours + "H";
      if (minutes) out += minutes + "M";
      return out + secs + "S";
    }
    return pad(hours) + ":" + pad(minutes) + ":" + pad(secs) + ".00";
  }

  /* Accepts either profile's format regardless of the declared version: content in the
     wild is not consistent about this, and a misread total silently loses a learner's time. */
  function parseDuration(value) {
    if (!value) return 0;
    var iso = /^P(?:([0-9.]+)Y)?(?:([0-9.]+)M)?(?:([0-9.]+)D)?(?:T(?:([0-9.]+)H)?(?:([0-9.]+)M)?(?:([0-9.]+)S)?)?$/.exec(value);
    if (iso) {
      return (parseFloat(iso[1] || 0) * 31536000) + (parseFloat(iso[2] || 0) * 2592000) + (parseFloat(iso[3] || 0) * 86400) +
        (parseFloat(iso[4] || 0) * 3600) + (parseFloat(iso[5] || 0) * 60) + parseFloat(iso[6] || 0);
    }
    var hhmmss = /^(\\d+):(\\d{1,2}):(\\d{1,2}(?:\\.\\d+)?)$/.exec(value);
    if (hhmmss) {
      return (parseInt(hhmmss[1], 10) * 3600) + (parseInt(hhmmss[2], 10) * 60) + parseFloat(hhmmss[3]);
    }
    return 0;
  }

  /* ---- Data model ------------------------------------------------------ */

  var previous = load();
  var data = {};
  var defaults = IS_2004 ? DEFAULTS_2004 : DEFAULTS_12;
  var key;
  for (key in defaults) if (defaults.hasOwnProperty(key)) data[key] = defaults[key];
  for (key in previous) if (previous.hasOwnProperty(key)) data[key] = previous[key];

  var baseTotalSeconds = parseDuration(previous[B.totalTime] || "");

  data[B.learnerId] = config.learnerId || "anonymous";
  data[B.learnerName] = config.learnerName || "Anonymous";
  if (config.masteryScore !== undefined && config.masteryScore !== null && config.masteryScore !== "") {
    data[B.masteryScore] = String(config.masteryScore);
  }
  /* A SCO reads cmi.entry to decide whether to resume or start over. */
  data[B.entry] = (previous[B.exit] === "suspend" || previous[B.location]) ? "resume" : "ab-initio";

  var initialised = false;
  var terminated = false;
  var lastError = "0";

  var ERROR_STRINGS = {
    "0": "No error",
    "101": "General exception",
    "122": "Retrieve data before initialization",
    "132": "Store data before initialization",
    "301": "Not initialized",
    "403": "Element is read only",
    "404": "Element is write only"
  };

  function countOf(prefix) {
    var pattern = new RegExp("^" + prefix.replace(/\\./g, "\\\\.") + "\\\\.(\\\\d+)\\\\.");
    var highest = -1;
    for (var element in data) {
      if (!data.hasOwnProperty(element)) continue;
      var match = pattern.exec(element);
      if (match) highest = Math.max(highest, parseInt(match[1], 10));
    }
    return String(highest + 1);
  }

  function totalSeconds() {
    return baseTotalSeconds + parseDuration(data[B.sessionTime] || "");
  }

  function save() {
    var snapshot = {};
    for (var element in data) if (data.hasOwnProperty(element)) snapshot[element] = data[element];
    snapshot[B.totalTime] = formatDuration(totalSeconds());
    persist(snapshot);
  }

  function endsWith(value, suffix) {
    return value.length >= suffix.length && value.slice(value.length - suffix.length) === suffix;
  }

  function doInitialize() {
    if (initialised) { lastError = "101"; return "false"; }
    initialised = true;
    lastError = "0";
    return "true";
  }

  function doTerminate() {
    if (!initialised || terminated) { lastError = "301"; return "false"; }
    terminated = true;
    save();
    lastError = "0";
    return "true";
  }

  function doGetValue(element) {
    if (!initialised || terminated) { lastError = "122"; return ""; }
    if (CHILDREN.hasOwnProperty(element)) { lastError = "0"; return CHILDREN[element]; }
    if (endsWith(element, "._count")) {
      lastError = "0";
      return countOf(element.slice(0, element.length - "._count".length));
    }
    if (contains(writeOnly, element)) { lastError = "404"; return ""; }
    lastError = "0";
    return data.hasOwnProperty(element) ? data[element] : "";
  }

  function doSetValue(element, value) {
    if (!initialised || terminated) { lastError = "132"; return "false"; }
    if (contains(readOnly, element) || endsWith(element, "._count") || CHILDREN.hasOwnProperty(element)) {
      lastError = "403";
      return "false";
    }
    data[element] = String(value);
    lastError = "0";
    return "true";
  }

  function doCommit() {
    if (!initialised || terminated) { lastError = "301"; return "false"; }
    save();
    lastError = "0";
    return "true";
  }

  function getLastError() { return lastError; }
  function getErrorString(code) { return ERROR_STRINGS[String(code)] || ""; }

  if (IS_2004) {
    global.API_1484_11 = {
      Initialize: doInitialize,
      Terminate: doTerminate,
      GetValue: doGetValue,
      SetValue: doSetValue,
      Commit: doCommit,
      GetLastError: getLastError,
      GetErrorString: getErrorString,
      GetDiagnostic: getErrorString
    };
  } else {
    global.API = {
      LMSInitialize: doInitialize,
      LMSFinish: doTerminate,
      LMSGetValue: doGetValue,
      LMSSetValue: doSetValue,
      LMSCommit: doCommit,
      LMSGetLastError: getLastError,
      LMSGetErrorString: getErrorString,
      LMSGetDiagnostic: getErrorString
    };
  }

  /* Content that navigates away without terminating would otherwise lose the attempt. */
  global.addEventListener("pagehide", function () {
    if (initialised && !terminated) save();
  });
})(window);
`;
}
