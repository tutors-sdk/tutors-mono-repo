/**
 * The client-side half of a SCORM export: the files that talk to the LMS.
 *
 * Three artefacts are generated into the package root:
 *
 *  - `index.html`        the SCO itself: a wrapper page holding one full-viewport iframe
 *  - `scorm-runtime.js`  loaded by the wrapper; owns the LMS session
 *  - `scorm-page.js`     loaded by every content page; reports "I am page N" upwards
 *
 * The wrapper exists because a Tutors course is many HTML pages but only one SCO. If each
 * page talked to the LMS directly, every navigation would mean Initialize/Terminate on the
 * same API instance, which SCORM forbids and most LMSs reject after the first cycle. With
 * a wrapper the session is opened once, stays open while the learner moves around inside
 * the iframe, and closes once — so the LMS sees a single coherent attempt and one
 * session time rather than a burst of tiny ones.
 *
 * Generated code is emitted as ES5 string concatenation, deliberately: it has to run in
 * whatever browser the LMS supports, and avoiding template literals keeps the generator's
 * own template literals readable.
 */

import type { ScormVersion } from "@tutors/tutors-model-lib";
import { escapeXml } from "./manifest.ts";

/** Directory inside the package that holds the generated static site. */
export const CONTENT_FOLDER = "content";
/** Launch file of the SCO, relative to the package root. */
export const WRAPPER_FILE = "index.html";
/** Session-owning script, loaded by the wrapper only. */
export const RUNTIME_FILE = "scorm-runtime.js";
/** Per-page reporting script, injected into every content page. */
export const PAGE_FILE = "scorm-page.js";

export interface ScormRuntimeOptions {
  version: ScormVersion;
  /** Number of trackable content pages; the denominator for progress. */
  totalPages: number;
  /** Page the wrapper opens when the LMS has no resume location. */
  entryPage?: string;
}

/**
 * The SCO launch page.
 *
 * Kept deliberately bare — no CDN references, no styling beyond making the frame fill the
 * viewport — so that it still renders if the LMS blocks outbound requests. Everything the
 * learner actually sees comes from the framed content.
 */
export function buildWrapperHtml(title: string, options: ScormRuntimeOptions): string {
  const entryPage = options.entryPage || "index.html";
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${escapeXml(title)}</title>
    <style>
      html, body { margin: 0; padding: 0; height: 100%; overflow: hidden; }
      #tutors-scorm-frame { display: block; border: 0; width: 100%; height: 100%; }
    </style>
    <script src="${RUNTIME_FILE}"></script>
  </head>
  <body>
    <iframe id="tutors-scorm-frame" name="tutors-scorm-frame" title="${escapeXml(title)}" src="${CONTENT_FOLDER}/${entryPage}"></iframe>
  </body>
</html>
`;
}

/**
 * Session-owning script for the wrapper.
 *
 * Progress is tracked as a bitfield over the ordered page list rather than a list of
 * visited routes: SCORM 1.2 caps `cmi.suspend_data` at 4096 characters, which a course
 * of any size would overrun if routes were stored verbatim. One bit per page keeps even
 * a thousand-page course inside a couple of hundred base64 characters.
 */
export function buildRuntimeScript(options: ScormRuntimeOptions): string {
  const is2004 = options.version === "2004";
  const total = Math.max(options.totalPages, 1);

  // Data-model element names and API method names differ between the two profiles.
  const cfg = is2004
    ? {
      finder: "API_1484_11",
      initialize: "Initialize",
      getValue: "GetValue",
      setValue: "SetValue",
      commit: "Commit",
      terminate: "Terminate",
      lastError: "GetLastError",
      location: "cmi.location",
      status: "cmi.completion_status",
      sessionTime: "cmi.session_time",
      exit: "cmi.exit",
    }
    : {
      finder: "API",
      initialize: "LMSInitialize",
      getValue: "LMSGetValue",
      setValue: "LMSSetValue",
      commit: "LMSCommit",
      terminate: "LMSFinish",
      lastError: "LMSGetLastError",
      location: "cmi.core.lesson_location",
      status: "cmi.core.lesson_status",
      sessionTime: "cmi.core.session_time",
      exit: "cmi.core.exit",
    };

  return `/* Generated by Tutors. SCORM ${options.version} run-time adapter. */
(function (global) {
  "use strict";

  var TOTAL_PAGES = ${total};
  var IS_2004 = ${is2004};
  var COMMIT_INTERVAL_SECONDS = 60;

  var api = null;
  var started = false;
  var finished = false;
  var elapsedSeconds = 0;
  var secondsSinceCommit = 0;
  var visited = newBitfield();

  /* ---- LMS discovery -------------------------------------------------- */

  /* The standard search: up the frame ancestors, then across to the opener. */
  function findAPI(win) {
    var depth = 0;
    while (win && depth < 500) {
      if (win.${cfg.finder}) return win.${cfg.finder};
      if (win.parent === win) return null;
      win = win.parent;
      depth += 1;
    }
    return null;
  }

  function locateAPI() {
    var found = findAPI(global);
    if (!found && global.opener && !global.opener.closed) found = findAPI(global.opener);
    return found;
  }

  /* ---- API wrappers --------------------------------------------------- */

  /* Every call is guarded: a misbehaving LMS must not break the content. */
  function call(name, a, b) {
    if (!api) return "";
    try {
      return b === undefined ? api[name](a) : api[name](a, b);
    } catch (e) {
      log("call to " + name + " threw", e);
      return "";
    }
  }

  function get(element) {
    return String(call("${cfg.getValue}", element) || "");
  }

  function set(element, value) {
    call("${cfg.setValue}", element, String(value));
  }

  function commit() {
    call("${cfg.commit}", "");
    secondsSinceCommit = 0;
  }

  function log(message, detail) {
    if (global.console && global.console.warn) global.console.warn("[tutors-scorm] " + message, detail || "");
  }

  /* ---- Visited-page bitfield ------------------------------------------ */

  function newBitfield() {
    var bytes = [];
    for (var i = 0; i < Math.ceil(TOTAL_PAGES / 8); i += 1) bytes.push(0);
    return bytes;
  }

  /*
   * Decode "v1:<total>:<base64>". Anything unrecognised — an older format, a different
   * page count after a rebuild, or a truncated value — is treated as no progress rather
   * than as an error, so a republished course degrades to starting over instead of
   * reporting nonsense.
   */
  function decodeVisited(raw) {
    var bytes = newBitfield();
    if (!raw) return bytes;
    var parts = raw.split(":");
    if (parts.length !== 3 || parts[0] !== "v1" || parseInt(parts[1], 10) !== TOTAL_PAGES) return bytes;
    try {
      var binary = global.atob(parts[2]);
      for (var i = 0; i < bytes.length && i < binary.length; i += 1) {
        bytes[i] = binary.charCodeAt(i) & 255;
      }
    } catch (e) {
      log("suspend_data could not be decoded; restarting progress", e);
      return newBitfield();
    }
    /* The last byte has room for pages the course does not have. Corrupted data with
       those bits set would push the visited count above the total, and so report a
       progress measure above 1, which a conformant LMS rejects. */
    var spare = bytes.length * 8 - TOTAL_PAGES;
    if (spare > 0) bytes[bytes.length - 1] &= 255 >> spare;
    return bytes;
  }

  function encodeVisited(bytes) {
    var binary = "";
    for (var i = 0; i < bytes.length; i += 1) binary += String.fromCharCode(bytes[i]);
    return "v1:" + TOTAL_PAGES + ":" + global.btoa(binary);
  }

  function markVisited(bytes, index) {
    if (index < 0 || index >= TOTAL_PAGES) return false;
    var byte = index >> 3;
    var mask = 1 << (index & 7);
    if (bytes[byte] & mask) return false;
    bytes[byte] |= mask;
    return true;
  }

  function countVisited(bytes) {
    var count = 0;
    for (var i = 0; i < bytes.length; i += 1) {
      var byte = bytes[i];
      while (byte) {
        count += byte & 1;
        byte >>= 1;
      }
    }
    return count;
  }

  /* ---- Session time --------------------------------------------------- */

  function pad(value, width) {
    var out = String(value);
    while (out.length < width) out = "0" + out;
    return out;
  }

  /* SCORM 1.2 wants HHHH:MM:SS.SS; SCORM 2004 wants an ISO-8601 duration. */
  function formatSessionTime(seconds) {
    var hours = Math.floor(seconds / 3600);
    var minutes = Math.floor((seconds % 3600) / 60);
    var secs = Math.floor(seconds % 60);
    if (IS_2004) {
      var out = "PT";
      if (hours) out += hours + "H";
      if (minutes) out += minutes + "M";
      return out + secs + "S";
    }
    return pad(hours, 2) + ":" + pad(minutes, 2) + ":" + pad(secs, 2) + ".00";
  }

  /* ---- Progress reporting --------------------------------------------- */

  function reportProgress() {
    var count = countVisited(visited);
    var complete = count >= TOTAL_PAGES;
    set("${cfg.status}", complete ? "completed" : "incomplete");
    if (IS_2004) {
      set("cmi.progress_measure", (count / TOTAL_PAGES).toFixed(4));
    }
    set("cmi.suspend_data", encodeVisited(visited));
    return complete;
  }

  /* ---- Lifecycle ------------------------------------------------------ */

  function start() {
    api = locateAPI();
    if (!api) {
      log("no SCORM API found; running unreported");
      return;
    }
    if (String(call("${cfg.initialize}", "")) !== "true") {
      log("LMS refused to initialise, error " + call("${cfg.lastError}", ""));
      api = null;
      return;
    }
    started = true;
    visited = decodeVisited(get("cmi.suspend_data"));
    reportProgress();
    commit();
    global.setInterval(tick, 1000);
  }

  /* Only count time the learner could actually see the content. */
  function tick() {
    if (finished || global.document.hidden) return;
    elapsedSeconds += 1;
    secondsSinceCommit += 1;
    if (secondsSinceCommit >= COMMIT_INTERVAL_SECONDS) {
      set("${cfg.sessionTime}", formatSessionTime(elapsedSeconds));
      commit();
    }
  }

  function finish() {
    if (!started || finished) return;
    finished = true;
    var complete = reportProgress();
    set("${cfg.sessionTime}", formatSessionTime(elapsedSeconds));
    /* "suspend" preserves suspend_data for the next attempt; a finished course does not need it. */
    set("${cfg.exit}", complete ? "" : "suspend");
    commit();
    call("${cfg.terminate}", "");
  }

  /* ---- Public surface, used by scorm-page.js in the framed content ----- */

  var TutorsScorm = {
    /* Called by each content page as it loads. */
    visit: function (index, path) {
      if (path) set("${cfg.location}", path);
      var isNew = markVisited(visited, index);
      reportProgress();
      if (isNew) commit();
    },
    /* Where the learner left off, so the wrapper can reopen it. */
    resumeLocation: function () {
      return started ? get("${cfg.location}") : "";
    },
  };

  global.TutorsScorm = TutorsScorm;

  start();

  /* pagehide rather than beforeunload: beforeunload disqualifies the page from the
     back/forward cache and is unreliable on mobile Safari. */
  global.addEventListener("pagehide", finish);

  global.addEventListener("DOMContentLoaded", function () {
    var frame = global.document.getElementById("tutors-scorm-frame");
    var resume = TutorsScorm.resumeLocation();
    if (frame && resume) frame.setAttribute("src", "${CONTENT_FOLDER}/" + resume);
  });
})(window);
`;
}

/**
 * Injected into every content page.
 *
 * Intentionally tiny and failure-tolerant: content pages are also served standalone by
 * `tutors-lite`, and a page must render identically whether or not there is an LMS above it.
 */
export function buildPageScript(): string {
  return `/* Generated by Tutors. Reports page visits to the SCORM wrapper. */
(function () {
  "use strict";
  var script = document.currentScript;
  if (!script) return;
  var index = parseInt(script.getAttribute("data-scorm-index"), 10);
  var path = script.getAttribute("data-scorm-path") || "";
  if (isNaN(index)) return;
  try {
    /* Same-origin by construction, but a sandboxed frame can still make this throw. */
    if (window.parent !== window && window.parent.TutorsScorm) {
      window.parent.TutorsScorm.visit(index, path);
    }
  } catch (e) {
    /* Not running inside the wrapper — nothing to report to. */
  }
})();
`;
}

/**
 * Build the script tag injected into a single content page.
 *
 * @param pagePath page location relative to the content folder, forward-slashed
 * @param index the page's position in the ordered page list, i.e. its bit in the bitfield
 */
export function buildPageScriptTag(pagePath: string, index: number): string {
  const depth = pagePath.split("/").length - 1;
  // Content lives one level below the package root, hence the extra "../".
  const root = "../".repeat(depth + 1);
  return `<script src="${root}${PAGE_FILE}" data-scorm-index="${index}" data-scorm-path="${escapeXml(pagePath)}"></script>`;
}
