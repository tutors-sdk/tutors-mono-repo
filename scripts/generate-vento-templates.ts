/**
 * Writes packages/jsr/gen/src/templates/vento-templates.ts from the .vto files beside it, so the
 * static generator (tutors-lite) renders with the templates of its own release. A published JSR or
 * npm package cannot read sibling files by path, which is why they ship as a module.
 *
 *   pnpm generate:vento-templates
 *
 * tests/bdd/features/generator/static-build.feature (Rule 0693) fails when the module and the
 * .vto files differ.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { REPO_ROOT } from "./checks/lib/repo.ts";

export const VENTO_DIR = join(REPO_ROOT, "packages/jsr/gen/src/templates/vento");
export const VENTO_MODULE = join(REPO_ROOT, "packages/jsr/gen/src/templates/vento-templates.ts");

function vtoFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return vtoFiles(full);
    return entry.name.endsWith(".vto") ? [full] : [];
  });
}

/** Every template under `dir` (default VENTO_DIR), keyed by its path relative to that folder, in sorted order. */
export function readVentoTemplates(dir: string = VENTO_DIR): Record<string, string> {
  const entries = vtoFiles(dir)
    .map((file) => [relative(dir, file).split(sep).join("/"), readFileSync(file, "utf8")] as const)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(entries);
}

export function moduleText(templates: Record<string, string> = readVentoTemplates()): string {
  const body = Object.entries(templates)
    .map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`)
    .join("\n");
  return [
    "// Generated by scripts/generate-vento-templates.ts from the .vto files in ./vento. Do not edit:",
    "// change the .vto file and run `pnpm generate:vento-templates`.",
    "export const ventoTemplates: Readonly<Record<string, string>> = {",
    body,
    "};",
    ""
  ].join("\n");
}

if (process.argv[1]?.endsWith("generate-vento-templates.ts")) {
  writeFileSync(VENTO_MODULE, moduleText());
  process.stdout.write(`wrote ${VENTO_MODULE}\n`);
}
