import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { TUTORS_JSON_SCHEMA } from "../packages/jsr/types/src/tutors-json.ts";

export const validatorSchemaPath = fileURLToPath(new URL("../apps/validator/src/lib/course-schema.js", import.meta.url));

/** Compile at build time so course validation works under CSP without unsafe-eval. */
export function validatorSchemaText(): string {
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
  return `/* eslint-disable */\n// @ts-nocheck\n// Generated by scripts/generate-validator-schema.ts. Do not edit.\n${standalone(ajv, ajv.compile(TUTORS_JSON_SCHEMA))}\n`;
}

if (process.argv[1]?.endsWith("generate-validator-schema.ts")) writeFileSync(validatorSchemaPath, validatorSchemaText());
